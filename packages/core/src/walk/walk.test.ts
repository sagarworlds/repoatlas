import { mkdir, mkdtemp, rm, symlink, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { AnalysisError } from "../errors.ts";
import { DEFAULT_LIMITS } from "../types.ts";
import { isGeneratedPath, looksBinary, looksMinifiedOrGenerated } from "./filters.ts";
import { checkSourceContent, walkRepo } from "./walker.ts";

describe("filters", () => {
  it("flags generated paths and lockfiles", () => {
    expect(isGeneratedPath("web/app.min.js")).toBe("generated-path");
    expect(isGeneratedPath("api/x.pb.go")).toBe("generated-path");
    expect(isGeneratedPath("api/types_gen.go")).toBe("generated-path");
    expect(isGeneratedPath("api/zz_generated.deepcopy.go")).toBe("generated-path");
    expect(isGeneratedPath("x_pb2.py")).toBe("generated-path");
    expect(isGeneratedPath("a/b/pnpm-lock.yaml")).toBe("lockfile");
    expect(isGeneratedPath("go.sum")).toBe("lockfile");
    expect(isGeneratedPath("src/app.ts")).toBeUndefined();
  });

  it("detects NUL bytes only within the first 8000 bytes", () => {
    expect(looksBinary(Buffer.from([65, 0, 66]))).toBe("binary");
    expect(looksBinary(Buffer.from("plain text"))).toBeUndefined();
    const late = Buffer.alloc(9000, 65);
    late[8500] = 0;
    expect(looksBinary(late)).toBeUndefined();
  });

  it("detects minified and generated content", () => {
    expect(looksMinifiedOrGenerated("x".repeat(10_001))).toBe("minified");
    expect(looksMinifiedOrGenerated(`${"x".repeat(400)}\n${"y".repeat(400)}`)).toBe("minified");
    expect(looksMinifiedOrGenerated("// @generated by tool\nconst a = 1;\n")).toBe(
      "generated-marker",
    );
    expect(looksMinifiedOrGenerated("// Code. DO NOT EDIT.\npackage x\n")).toBe("generated-marker");
    expect(looksMinifiedOrGenerated("const a = 1;\nconst b = 2;\n")).toBeUndefined();
    expect(looksMinifiedOrGenerated("")).toBeUndefined();
  });

  it("checkSourceContent delegates to the content check", async () => {
    expect(await checkSourceContent("x".repeat(10_001))).toBe("minified");
    expect(await checkSourceContent("ok\n")).toBeUndefined();
  });
});

describe("walkRepo", () => {
  let root: string;
  beforeEach(async () => {
    root = await mkdtemp(join(tmpdir(), "repoatlas-walk-"));
  });
  afterEach(async () => {
    await rm(root, { recursive: true, force: true });
  });

  async function put(rel: string, data: string | Buffer): Promise<void> {
    const abs = join(root, rel);
    await mkdir(join(abs, ".."), { recursive: true });
    await writeFile(abs, data);
  }

  it("returns sorted POSIX paths and counts skips by reason", async () => {
    await put("src/b.ts", "b");
    await put("src/a.ts", "aa");
    await put("Z.ts", "z");
    await put("node_modules/x/index.js", "x");
    await put("src/vendor/lib.js", "x");
    await put("pnpm-lock.yaml", "x");
    await put("bundle.min.js", "x");
    await put("logo.png", Buffer.from([1, 0, 2]));
    await put("big.ts", "x".repeat(200));

    const result = await walkRepo(root, { ...DEFAULT_LIMITS, maxFileBytes: 100 });
    expect(result.files).toEqual([
      { path: "Z.ts", bytes: 1 },
      { path: "src/a.ts", bytes: 2 },
      { path: "src/b.ts", bytes: 1 },
    ]);
    const counts = Object.fromEntries(result.skipped.map((s) => [s.reason, s.count]));
    expect(counts).toEqual({
      binary: 1,
      "generated-path": 1,
      "ignored-dir": 2,
      lockfile: 1,
      "too-large": 1,
    });
  });

  it("never follows symlinks", async () => {
    await put("real/a.ts", "a");
    try {
      await symlink(join(root, "real"), join(root, "linkdir"), "junction");
      await symlink(join(root, "real", "a.ts"), join(root, "link.ts"), "file");
    } catch {
      return; // symlink creation not permitted on this machine
    }
    const result = await walkRepo(root, DEFAULT_LIMITS);
    expect(result.files.map((f) => f.path)).toEqual(["real/a.ts"]);
    expect(result.skipped.find((s) => s.reason === "symlink")?.count).toBeGreaterThanOrEqual(1);
  });

  it("throws REPO_TOO_LARGE past maxFiles and CANCELLED on abort", async () => {
    await put("a.ts", "a");
    await put("b.ts", "b");
    await expect(walkRepo(root, { ...DEFAULT_LIMITS, maxFiles: 1 })).rejects.toMatchObject({
      code: "REPO_TOO_LARGE",
    });
    const controller = new AbortController();
    controller.abort();
    const err = await walkRepo(root, DEFAULT_LIMITS, controller.signal).catch((e: unknown) => e);
    expect(err).toBeInstanceOf(AnalysisError);
    expect((err as AnalysisError).code).toBe("CANCELLED");
  });
});
