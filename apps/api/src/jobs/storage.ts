import path from "node:path";
import { z } from "zod";

const SHA_RE = /^[0-9a-f]{40}$/;

/** Layout of DATA_DIR. All paths are absolute because `dataDir` is. */
export function sourcesRoot(dataDir: string): string {
  return path.join(dataDir, "sources");
}

export function tmpRoot(dataDir: string): string {
  return path.join(dataDir, "tmp");
}

/** DATA_DIR/sources/{sha}. The sha is validated so it can never contain path separators. */
export function sourcesDirFor(dataDir: string, commitSha: string): string {
  if (!SHA_RE.test(commitSha)) throw new Error("Invalid commit SHA");
  return path.join(sourcesRoot(dataDir), commitSha);
}

/** DATA_DIR/tmp/{analysisId}. Analysis ids are generated by us ("an_" + ULID). */
export function tmpDirFor(dataDir: string, analysisId: string): string {
  if (!/^an_[0-9A-Za-z]+$/.test(analysisId)) throw new Error("Invalid analysis id");
  return path.join(tmpRoot(dataDir), analysisId);
}

/**
 * What the `error` column holds. The store has a single text column, so code and message
 * are stored together as JSON and split again when the API responds.
 */
export const StoredErrorSchema = z.object({ code: z.string(), message: z.string() });
export type StoredError = z.infer<typeof StoredErrorSchema>;

export function encodeError(code: string, message: string): string {
  return JSON.stringify({ code, message } satisfies StoredError);
}

export function decodeError(raw: string | null): StoredError | null {
  if (raw === null) return null;
  try {
    const parsed = StoredErrorSchema.safeParse(JSON.parse(raw));
    if (parsed.success) return parsed.data;
  } catch {
    // fall through: not JSON
  }
  return { code: "INTERNAL", message: raw };
}
